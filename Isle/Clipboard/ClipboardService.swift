import AppKit
import Carbon.HIToolbox
import SwiftUI

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable { case text, link, image }
    let id = UUID()
    let kind: Kind
    let text: String?
    let image: NSImage?
    let png: Data?
    let date: Date
    let sourceApp: String?

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.id == b.id }

    var preview: String {
        switch kind {
        case .image: String(localized: "Image")
        default: (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        }
    }
}

/// Clipboard history, newest first. Memory only — gone after Isle quits, like Windows.
/// Items marked concealed / transient by password managers are never recorded.
@MainActor
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()
    static let limit = 50

    @Published private(set) var items: [ClipItem] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    /// changeCount of a write Isle made itself (re-pasting an old item), so it isn't re-recorded.
    private var ownChange: Int?

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("com.apple.is-remote-clipboard"),
    ]

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ownChange == pb.changeCount { return }
        let types = pb.types ?? []
        guard !types.contains(where: Self.skipTypes.contains) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(" ") && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
            insert(ClipItem(kind: isLink ? .link : .text, text: s, image: nil, png: nil, date: Date(), sourceApp: app))
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), let image = NSImage(data: data) {
            let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) ?? data
            insert(ClipItem(kind: .image, text: nil, image: image, png: png, date: Date(), sourceApp: app))
        }
    }

    private func insert(_ item: ClipItem) {
        if let text = item.text { items.removeAll { $0.text == text } }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Put an item back on the clipboard (and move it to the top).
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let text = item.text {
            pb.setString(text, forType: .string)
        } else if let png = item.png {
            pb.setData(png, forType: .png)
            if let tiff = item.image?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        }
        ownChange = pb.changeCount
        lastChange = pb.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items = [] }

    func debugInject(_ items: [ClipItem]) { self.items = items }
}

/// System-wide hotkey through Carbon (no permission needed).
final class GlobalHotKey {
    private var ref: EventHotKeyRef?
    private static var handlers: [UInt32: () -> Void] = [:]
    private static var installed = false
    private let id: UInt32

    init(keyCode: UInt32, modifiers: UInt32, id: UInt32, handler: @escaping () -> Void) {
        self.id = id
        Self.handlers[id] = handler
        Self.installHandler()
        let hotKeyID = EventHotKeyID(signature: OSType(0x4953_4C45), id: id) // 'ISLE'
        RegisterEventHotKey(keyCode, modifiers, hotKeyID, GetApplicationEventTarget(), 0, &ref)
    }

    deinit {
        if let ref { UnregisterEventHotKey(ref) }
        Self.handlers[id] = nil
    }

    private static func installHandler() {
        guard !installed else { return }
        installed = true
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
            var hk = EventHotKeyID()
            GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil,
                              MemoryLayout<EventHotKeyID>.size, nil, &hk)
            let id = hk.id
            DispatchQueue.main.async { GlobalHotKey.handlers[id]?() }
            return noErr
        }, 1, &spec, nil, nil)
    }
}
